// Creates the Creator and the two test users, and publishes the example
// exercise as the Creator. Run once after the security rules are deployed:
//   npm run seed
// Passwords are generated and kept in C:\AI\PROJECTS\_secrets\flightsim-test-users.env.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { initializeApp } from 'firebase/app';
import { createUserWithEmailAndPassword, getAuth, signInWithEmailAndPassword, signOut } from 'firebase/auth';
import { doc, getDoc, getFirestore, setDoc } from 'firebase/firestore';
import { firebaseConfig } from '../src/firebase/config';
import { seedExercise } from '../src/exercises/seed';

const SECRETS = 'C:/AI/PROJECTS/_secrets/flightsim-test-users.env';
const USERS = [
  { key: 'CREATOR', email: 'damefr+creator@hotmail.com', name: 'Creator', surname: 'Test', role: 'creator' },
  { key: 'TEST1', email: 'damefr+test1@hotmail.com', name: 'Test', surname: 'User One', role: 'user' },
  { key: 'TEST2', email: 'damefr+test2@hotmail.com', name: 'Test', surname: 'User Two', role: 'user' },
] as const;

const saved: Record<string, string> = {};
if (existsSync(SECRETS))
  for (const line of readFileSync(SECRETS, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (m) saved[m[1]] = m[2];
  }
for (const u of USERS) saved[`${u.key}_EMAIL`] = u.email;
for (const u of USERS) saved[`${u.key}_PASSWORD`] ||= randomBytes(9).toString('base64url');
writeFileSync(SECRETS, `# Test accounts of the flight simulator app (generated by scripts/seed.ts)\n${Object.entries(saved).map(([k, v]) => `${k}=${v}`).join('\n')}\n`);

const app = initializeApp(firebaseConfig);
const auth = getAuth(app);
const db = getFirestore(app);

async function account(email: string, password: string) {
  try {
    return (await createUserWithEmailAndPassword(auth, email, password)).user;
  } catch (e) {
    if ((e as { code?: string }).code !== 'auth/email-already-in-use') throw e;
    return (await signInWithEmailAndPassword(auth, email, password)).user;
  }
}

for (const u of USERS) {
  const user = await account(u.email, saved[`${u.key}_PASSWORD`]);
  const ref = doc(db, 'users', user.uid);
  if (!(await getDoc(ref)).exists())
    await setDoc(ref, { email: u.email, name: u.name, surname: u.surname, role: u.role, canVote: true, canReview: true, disabled: false, createdAt: Date.now() });
  console.log(`account ready: ${u.email} (${u.role})`);
  if (u.role === 'creator') {
    const ex = seedExercise();
    const exRef = doc(db, 'exercises', ex.id);
    if ((await getDoc(exRef)).exists()) console.log('example exercise already published');
    else {
      const now = Date.now();
      await setDoc(exRef, {
        name: ex.name,
        description: ex.description,
        ownerId: user.uid,
        ownerName: `${u.name} ${u.surname}`,
        content: JSON.parse(JSON.stringify(ex.content)),
        updatedAt: now,
        visibility: 'public',
        sharedWith: [],
        version: 1,
        publishedAt: now,
        releaseNote: ex.releaseNote,
        hasDraft: false,
      });
      console.log(`example exercise published (public): ${ex.name}`);
    }
  }
  await signOut(auth);
}
console.log(`passwords: ${SECRETS}`);
process.exit(0);
